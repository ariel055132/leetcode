public class Q1952 {
    public boolean isThree(int n) {
        /**
         * (4 -> 1, 2, 4)
         * 5 -> 1, 5
         * 6 -> 1, 2, 3, 6
         * 7 -> 1, 7
         * 8 -> 1, 2, 4, 8
         * (9 -> 1, 3, 9)
         * 10 -> 1, 2, 5, 10
         * 11 -> 1, 11
         * 12 -> 1, 2, 3, 4, 6, 12
         * 13 -> 1, 13
         * 14 -> 1, 14
         * 15 -> 1, 3, 5, 15
         * 16 -> 1, 2, 4, 8, 16
         * 17 -> 1, 17
         * 18 -> 1, 2, 3, 6, 9, 18
         * 19 -> 1, 19
         * 20 -> 1, 2, 4, 5, 10, 20
         * 21 -> 1, 3, 7, 21
         * 22 -> 1, 2, 11, 22
         * 23 -> 1, 23
         * 24 -> 1, 2, 3, 4, 6, 8, 12, 24
         * 25 -> (1, 5, 25)
         */
        int divisors = 2; // whole number and 1
        for (int i = 2; i < n && divisors <= 3; i++) {
            if (n % i == 0) {
                divisors++;
            }
        }
        return divisors == 3;
    }
}
